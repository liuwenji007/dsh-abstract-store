#!/usr/bin/env node
/**
 * Emit the browser artifact `client.js` from the catalog data and the UI source.
 *
 * The host loads a plugin's Client half as one classic script that calls
 * `window.__ModuleLoader__.load({ id, factory })` and cannot resolve local
 * `import`s. So the merge + wrapper live here:
 *
 *   src/client.js (UI, plain statements)  +  data (snapshot ⨯ curation)
 *     -> client.js (committed; CI checks that rebuilding produces no diff)
 *
 * Editing the UI means editing `src/client.js`. Editing the catalog means
 * editing `data/curation.json` (or re-running `npm run sync`). Never edit the
 * generated `client.js` by hand.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadCatalog, ROOT } from './lib/data.mjs'

const PACKAGE_ID = 'dsh-abstract-index'
const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')

function main() {
  const catalog = loadCatalog(ROOT)
  const sourcePath = path.join(root, 'src', 'client.js')
  const source = fs.readFileSync(sourcePath, 'utf8')

  const moduleStatement = /^[ \t]*(?:import|export)[ \t]/m
  if (moduleStatement.test(source)) {
    throw new Error('src/client.js must contain plain statements only (no import/export): it is concatenated into the loader factory')
  }

  const dataLiteral = JSON.stringify(catalog)
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029')

  const output = `/* Generated by scripts/build-client.mjs — edit src/client.js and data/curation.json, then npm run build. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PACKAGE_ID)},
  factory(require) {
    const React = require('react');
    const DATA = ${dataLiteral};
${source.trim()}
    return plugin;
  },
});
`

  const target = path.join(root, 'client.js')
  fs.writeFileSync(target, output, 'utf8')

  const included = catalog.counts.included
  const excluded = catalog.counts.excluded
  console.log(`build: wrote ${path.relative(root, target)} (${(output.length / 1024).toFixed(1)} KiB)`)
  console.log(`  entries ${catalog.counts.audited} · included ${included} · excluded ${excluded}`)
  console.log(`  upstream ${catalog.upstream.commitShort ?? '(unknown)'} · synced ${catalog.generatedAt}`)
}

main()
